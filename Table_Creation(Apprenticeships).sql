Create Table Apprenticeships(
	Vacancy_refrence_number BIGINT NOT NULL,
	current_status VARCHAR(30) check(current_status IN ('Archived','Closed','Live','Submitted')),
	date_posted Date,
	Vacancy_title VARCHAR(100),
	Vacancy_description VARCHAR(150),
	Skills_required VARCHAR(100),
	qualifications_required VARCHAR(200),
	number_of_positions smallint,
	application_closing_date Date,
	expected_start_date Date,
	employer_full_name VARCHAR(50),
	provider_full_name VARCHAR(50),
	Vacancy_postcode VARCHAR(10),
	Vacancy_town VARCHAR(50),
	wage_type VARCHAR(50),
	hours_per_week NUMERIC(4,2),
	expected_duration VARCHAR(20),
	apprenticeship_type VARCHAR(50),
	training_type VARCHAR(20),
	framework_or_standard_name VARCHAR(50),
	Primary key(Vacancy_refrence_number));
